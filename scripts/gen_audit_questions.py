def parse_rows():
    rows = []
    for n, line in enumerate(RAW.strip().split("\n"), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("|")
        if len(parts) != 7:
            raise ValueError("第 %d 行字段数为 %d（应为 7）: %s" % (n, len(parts), line[:80]))
        rows.append([x.strip() for x in parts])
    return rows


def build():
    out, errs = [], []
    seen_q = set()
    tmap = {"c": "choice", "m": "multi", "j": "judge", "e": "essay"}
    for i, (typ, ch, topic, question, opts, ans, exp) in enumerate(parse_rows(), 1):
        qid = "auq%03d" % i
        if typ not in tmap:
            errs.append("%s 题型非法: %s" % (qid, typ)); continue
        if not question or not exp:
            errs.append("%s 题干或解析为空" % qid)
        if question in seen_q:
            errs.append("%s 题干重复: %s" % (qid, question[:40]))
        seen_q.add(question)
        full_topic = ("全书综合 · " + topic) if ch == "0" else ("第%s章 %s" % (ch, topic))
        d = dict(id=qid, note=NOTE, topic=full_topic, question=question, type=tmap[typ])
        if typ == "e":
            d["answer"] = ans
            d["explanation"] = exp
        else:
            options = ["正确", "错误"] if typ == "j" else opts.split(";")
            if len(options) < 2 or len(options) != len(set(options)):
                errs.append("%s 选项数异常或重复" % qid)
            if typ in ("c", "j"):
                try:
                    a = int(ans)
                except ValueError:
                    errs.append("%s 答案非整数" % qid); a = -1
                if not (0 <= a < len(options)):
                    errs.append("%s 答案索引越界" % qid)
            else:
                try:
                    a = [int(x) for x in ans.split(",")]
                except ValueError:
                    errs.append("%s 多选答案格式错" % qid); a = []
                if len(a) < 2 or len(set(a)) != len(a) or any(x < 0 or x >= len(options) for x in a):
                    errs.append("%s 多选答案异常" % qid)
            d["options"] = options
            d["answer"] = a
            d["explanation"] = exp
        out.append(d)
    return out, errs


def shuffle_options(questions):
    """打散选项位置，避免正确答案长期集中在同一字母。

    解析均按选项内容描述、不引用 A/B/C/D，故重排选项不会造成解析错位。
    单选按固定的非递增序列轮换目标位置；多选以固定种子洗牌并重映射答案。
    幂等：每次都从原始 RAW 重新构建，序列与种子决定最终排列，重跑结果一致。
    """
    targets = [0, 1, 2, 3, 1, 3, 0, 2, 2, 0, 3, 1]
    k = 0
    for i, q in enumerate(questions):
        if q["type"] == "choice":
            t = targets[k % len(targets)] % len(q["options"])
            k += 1
            opts = q["options"]
            opts[q["answer"]], opts[t] = opts[t], opts[q["answer"]]
            q["answer"] = t
        elif q["type"] == "multi":
            opts = q["options"]
            order = list(range(len(opts)))
            random.Random(20261113 + i).shuffle(order)
            inverse = {old: new for new, old in enumerate(order)}
            q["options"] = [opts[j] for j in order]
            q["answer"] = sorted(inverse[a] for a in q["answer"])
    return questions


def validate(questions):
    errs = []
    for q in questions:
        if q["type"] in ("choice", "multi", "judge"):
            o = q["options"]
            a = q["answer"] if isinstance(q["answer"], list) else [q["answer"]]
            if len(o) != len(set(o)):
                errs.append(q["id"] + " 选项重复")
            if any(not isinstance(x, int) or x < 0 or x >= len(o) for x in a):
                errs.append(q["id"] + " 答案越界")
        if not q.get("explanation"):
            errs.append(q["id"] + " 解析为空")
    return errs


